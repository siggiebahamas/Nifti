# Writes dev/src/noorange.css: every orange / brown-orange colour in the built app's CSS becomes a yellow
# of the right weight (soft fill, line, bright fill, dark-yellow text). Idempotent: run after a build, then build again.
import re, colorsys, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(HERE, '..', '..', 'Nifti_Sept17.html'), encoding='utf-8').read()
css = re.sub(r'/\*.*?\*/', '', '\n'.join(re.findall(r'<style[^>]*>(.*?)</style>', html, re.S)), flags=re.S)
MK = re.compile(r'(^|[\s>+~(,])(\.(mk|f\d|h\d|hiw|pr-|faq|hero|login|footer|nav-links|cta|lp-|price|plan-|m2|m3|v3|v-|gate|tour|wiz|onb)|nav\.top|\.marketing|#view-(index|pricing|login|features))')
VALUE = re.compile(r'(-v|-n|num|amt|val|kpi|total|tot|sum)\b|\sb$|\sstrong$')
def hls(h):
    h = h.lstrip('#'); h = ''.join(c*2 for c in h) if len(h) == 3 else h
    r, g, b = (int(h[i:i+2], 16) / 255 for i in (0, 2, 4)); H, L, S = colorsys.rgb_to_hls(r, g, b); return H * 360, L, S
def orange(h):
    H, L, S = hls(h)
    if not (16 <= H <= 43.5): return False
    return (S >= .6 and L <= .93) if L >= .8 else S >= .35
def repl(h, prop, sel):
    H, L, S = hls(h)
    if prop == 'color':
        if L >= .62: return '#F2CC3D'
        return '#A88900' if VALUE.search(sel) else '#1F2329'
    if 'border' in prop or prop == 'outline' or prop.startswith('outline'):
        return '#F0D77A' if L >= .85 else '#E0B400'
    return '#FFF4C2' if L >= .9 else '#FBE38A' if L >= .75 else '#E5B800' if L >= .45 else '#C9A200'
def splitsel(sel):
    out, d, cur = [], 0, ''
    for ch in sel:
        d += {'(': 1, ')': -1}.get(ch, 0)
        if ch == ',' and d == 0: out.append(cur); cur = ''
        else: cur += ch
    out.append(cur); return [s.strip() for s in out if s.strip()]
def walk(text):
    out, i = [], 0
    while i < len(text):
        j = text.find('{', i)
        if j < 0: break
        sel = text[i:j].strip(); d, k = 1, j + 1
        while d and k < len(text):
            d += {'{': 1, '}': -1}.get(text[k], 0); k += 1
        body = text[j+1:k-1]
        if sel.startswith('@media'):
            inner = walk(body)
            if inner: out.append(sel + '{' + inner + '}')
        elif not sel.startswith('@'):
            parts = [p for p in splitsel(sel) if not MK.search(' ' + p) and not re.match(r'^(from|to|\d+%)$', p)]
            if parts:
                decls = []
                for dcl in body.split(';'):
                    if ':' not in dcl or '#' not in dcl: continue
                    p, v = dcl.split(':', 1); p = p.strip()
                    if p.startswith('--'): continue
                    hit = [False]
                    def sub(m):
                        if orange(m.group(0)): hit[0] = True; return repl(m.group(0), p, parts[-1])
                        return m.group(0)
                    nv = re.sub(r'#[0-9A-Fa-f]{6}\b|#[0-9A-Fa-f]{3}\b(?![0-9A-Fa-f])', sub, v)
                    if hit[0]: decls.append(p + ':' + nv.strip())
                if decls: out.append(', '.join(parts) + '{' + ';'.join(decls) + '}')
        i = k
    return '\n'.join(out)
res = walk(css)
tokens = '''#view-app, body{--warn:#A88900;--warn-soft:#FFF4C2;--lowstock:#8C7200;--lowstock-soft:#FFF4C2;--lowstock-fill:#E5B800;--clay:#17593A;--clay-soft:#E3EFE7;}
/* inline colours set in page templates */
#view-app [style*="color:#7A4E10"], #view-app [style*="color:#8a6210"], #view-app [style*="color:#8A6210"], #view-app [style*="color:#9C5A33"], #view-app [style*="color:#8A6142"], #view-app [style*="color:#9C5A2E"]{color:#1F2329 !important;}
#view-app [style*="background:#F5E3D7"], #view-app [style*="background:#FFF3CD"], #view-app [style*="background:#F3E8CB"]{background:#FFF4C2 !important;}
'''
out = '  /* ===== No orange anywhere: generated by dev/tools/gen_noorange.py ===== */\n' + tokens + res + '\n'
open(os.path.join(HERE, '..', 'src', 'noorange.css'), 'w', encoding='utf-8').write(out)
print('noorange.css', len(res.splitlines()), 'rules')
